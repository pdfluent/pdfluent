//! J-59: an XFA form can be filled in a release build, saved and reopened.
//!
//! The overlay's `commit_xfa_field_value` writes the value to the form's
//! datasets packet whether or not the `xfa-interactive` feature is compiled (the
//! Mac App Store build leaves it out). This runs it on unsigned
//! real-world XFA forms from the golden set (the signed ones — 0bf81862,
//! 5d6e30ad, e2bb8995, ff2723ed — refuse a full rewrite and are covered by
//! signed_documents_are_refused.rs).
//!
//! Runs in the `cargo-test` job on Linux, macOS and Windows.

use pdfluent_lib::{OpenDocument, XfaWriteRequest};
use std::fs;
use std::path::PathBuf;

fn manifest(rel: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(rel)
}

fn scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("pdfluent-xfa-fill-{}", std::process::id()));
    fs::create_dir_all(&dir).expect("scratch dir");
    dir.join(name)
}

/// Fill the first fillable, data-bound text field the way the overlay does,
/// save, reopen from disk and read the value back.
fn fill_save_reopen(fixture: &str) {
    let path = manifest(fixture);
    let mut doc = OpenDocument::open(path.to_str().unwrap()).expect("open XFA fixture");
    let model = doc.xfa_form_model().expect("XFA form model");
    let target = model
        .fields
        .iter()
        .find(|f| f.field_type == "text" && !f.read_only && !f.bind_none && !f.hidden)
        .unwrap_or_else(|| panic!("{fixture}: no fillable, data-bound text field"))
        .name
        .clone();

    let sentinel = "PDFLUENT J-59 release fill";
    let result = doc
        .commit_xfa_field_value(&XfaWriteRequest::Text { name: target.clone(), value: sentinel.into() })
        .expect("commit XFA field value");
    assert!(result.persisted_to_datasets, "{fixture}: the value reaches the datasets packet");
    assert!(doc.document_info().xfa_detected, "{fixture}: still an XFA form");

    let out = scratch(&format!("{}.pdf", fixture.replace('/', "_")));
    doc.save_to(out.to_str().unwrap()).expect("save filled XFA form");
    let mut reopened = OpenDocument::open(out.to_str().unwrap()).expect("reopen");
    let again = reopened.xfa_form_model().expect("XFA model after reopen");
    let field = again.fields.iter().find(|f| f.name == target).expect("field after reopen");
    assert_eq!(field.value, sentinel, "{fixture}: the filled value persists across save and reopen");
}

#[test]
fn xfa_fill_persists_on_an_unsigned_government_form() {
    fill_save_reopen("tests/golden/xfa-6e9eac47_imm5645e.pdf");
}

#[test]
fn xfa_fill_persists_on_a_second_unsigned_xfa_form() {
    fill_save_reopen("tests/golden/xfa-bda32eb1_pdf_0008.pdf");
}

/// J-59's fixture: generated by tests/fixtures/make_xfa_calc.py, one page, no
/// datasets packet. The first fill creates the packet; the typed value comes
/// back after save and reopen, and the form's read-only field refuses a write.
#[test]
fn xfa_fill_persists_on_a_generated_form_without_a_datasets_packet() {
    let path = manifest("tests/fixtures/xfa_calc_order.pdf");
    let mut doc = OpenDocument::open(path.to_str().unwrap()).expect("open the generated XFA form");
    let model = doc.xfa_form_model().expect("XFA form model");
    let field = |name: &str| model.fields.iter().find(|f| f.name == name).unwrap_or_else(|| panic!("field {name}"));
    assert!(!field("order.lines.quantity").read_only, "quantity is fillable");
    assert!(field("order.lines.internal_ref").read_only, "the reference is the form's own read-only field");

    doc.commit_xfa_field_value(&XfaWriteRequest::Text { name: "order.lines.quantity".into(), value: "4".into() })
        .expect("commit the quantity");
    let out = scratch("xfa_calc_order.pdf");
    doc.save_to(out.to_str().unwrap()).expect("save the filled form");

    let mut reopened = OpenDocument::open(out.to_str().unwrap()).expect("reopen");
    assert!(reopened.document_info().xfa_detected, "still an XFA form");
    let again = reopened.xfa_form_model().expect("XFA model after reopen");
    let quantity = again.fields.iter().find(|f| f.name == "order.lines.quantity").expect("quantity after reopen");
    assert_eq!(quantity.value, "4", "the typed quantity persists across save and reopen");
}
